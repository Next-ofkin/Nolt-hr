-- Upgrade only the auth-user provisioning function: fresh HR invitation provenance.
-- Prerequisites: 20261016120000_hr_invitation_lifecycle applied, sending disabled,
-- no QUEUED/SENDING invitations. Existing auth identities are not altered.
-- This function preserves the prior bootstrap behavior; the new provenance
-- binding is permitted ONLY on the original auth.users INSERT, never UPDATE.
-- Execute through controlled Supabase hosted migration after review.
CREATE OR REPLACE FUNCTION nolt_private.provision_auth_user() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE claimed UUID;
DECLARE creation_invite UUID;
BEGIN
 IF NEW.email IS NULL THEN RETURN NEW; END IF;
 -- An invitation can claim a fresh provider identity ONLY on auth.users INSERT.
 -- The secret is generated by the server before dispatch and never trusted from email alone.
 IF TG_OP = 'INSERT' AND NEW.raw_user_meta_data ? 'nolt_hr_creation_secret' THEN
  UPDATE public."HrInvitation" SET "creationSubject"=NEW.id
   WHERE email=lower(NEW.email)
     AND state='SENDING'
     AND "creationSubject" IS NULL
     AND "creationSecretHash"=encode(sha256(convert_to(NEW.raw_user_meta_data->>'nolt_hr_creation_secret','UTF8')),'hex')
   RETURNING id INTO creation_invite;
 END IF;
 INSERT INTO public."User" (id,email,name,role)
 VALUES (NEW.id,lower(NEW.email),left(COALESCE(NULLIF(trim(NEW.raw_user_meta_data->>'name'),''),split_part(NEW.email,'@',1)),160),'EMPLOYEE')
 ON CONFLICT(id) DO UPDATE SET email=EXCLUDED.email;
 INSERT INTO public."Identity" (id,"userId",issuer,subject)
 VALUES (gen_random_uuid(),NEW.id,'https://llslubzdkdnvhbatmfug.supabase.co/auth/v1',NEW.id::text)
 ON CONFLICT(issuer,subject) DO NOTHING;
 IF NEW.email_confirmed_at IS NOT NULL THEN
  UPDATE nolt_private.bootstrap_hr SET claimed_subject=NEW.id,claimed_at=now()
  WHERE email=lower(NEW.email) AND claimed_subject IS NULL RETURNING claimed_subject INTO claimed;
  IF claimed IS NOT NULL THEN
   UPDATE public."User" SET role='HR' WHERE id=NEW.id;
   INSERT INTO public."AuditEvent" (id,"actorId",action,"targetId",metadata)
   VALUES(gen_random_uuid(),NEW.id,'BOOTSTRAP_HR_PROVISIONED',NEW.id,'{"source":"verified_supabase_email"}');
   INSERT INTO public."OutboxEvent" (id,type,"targetId") VALUES(gen_random_uuid(),'BOOTSTRAP_HR_PROVISIONED',NEW.id);
  END IF;
 END IF;
 RETURN NEW;
END $$;

REVOKE ALL ON FUNCTION nolt_private.provision_auth_user() FROM PUBLIC,anon,authenticated,service_role,nolt_app;
