-- ============================================================
-- Nolt HR — 0019: force a PostgREST schema cache reload
--
-- Symptom: browser calls to RPCs that genuinely exist on the database
-- (correct signature, correct grants — verified directly against the
-- live schema) were returning 404 Not Found from PostgREST, e.g.
-- POST /rest/v1/rpc/save_form_definition_draft.
--
-- Cause: PostgREST caches the Postgres schema (including function
-- signatures) and only rebuilds that cache on a `NOTIFY pgrst, 'reload
-- schema'` event. The rapid sequence of migrations 0015-0018 applied
-- via `supabase db push` did not reliably trigger that notification,
-- so PostgREST kept serving routes from a stale cache that predated
-- some of the newer/hardened RPC definitions.
--
-- Fix: explicitly notify PostgREST to reload. This changes nothing
-- about the schema itself — no tables, columns, functions, or grants
-- are touched.
-- ============================================================

notify pgrst, 'reload schema';
